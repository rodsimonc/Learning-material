print("multiplicacion:", 7 * 3)
print("division:", 7 / 3)          # siempre da float
print("division entera:", 7 // 3)  # descarta decimales
print("resto (modulo):", 7 % 3)    # lo que sobra
print("potencia:", 2 ** 10)        # 2 elevado a 10
